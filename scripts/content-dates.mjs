#!/usr/bin/env node
// Maintains data/content-dates.json: the <lastmod> date for every sitemap URL.
// A URL's date only changes when the hash of its rendered inputs (template, data, render
// pipeline version) changes, so lastmod reflects real content changes instead of build time.
// Usage: node scripts/content-dates.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { sitemapRoutes, contentHash } from '../lib/sitemap.mjs';

const FILE = path.join(process.cwd(), 'data', 'content-dates.json');
const today = new Date().toISOString().slice(0, 10);
const current = fs.existsSync(FILE) ? JSON.parse(fs.readFileSync(FILE, 'utf8')) : { entries: {} };
const next = { _comment: 'Generated by scripts/content-dates.mjs. Do not edit by hand.', entries: {} };
let changed = 0;

for (const route of sitemapRoutes()) {
  const hash = contentHash(route);
  const prev = current.entries[route.path];
  if (prev && prev.hash === hash) next.entries[route.path] = prev;
  else {
    next.entries[route.path] = { hash, lastmod: today };
    changed++;
  }
}
const removed = Object.keys(current.entries).filter((k) => !next.entries[k]).length;

if (process.argv.includes('--check')) {
  if (changed || removed) {
    console.error(`content-dates.json is stale (${changed} changed/new, ${removed} removed). Run: node scripts/content-dates.mjs`);
    process.exit(1);
  }
  console.log(`content-dates.json up to date (${Object.keys(next.entries).length} URLs).`);
} else {
  fs.writeFileSync(FILE, JSON.stringify(next, null, 1));
  console.log(`content-dates.json: ${Object.keys(next.entries).length} URLs, ${changed} updated to ${today}, ${removed} removed.`);
}
